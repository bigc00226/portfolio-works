const file = path.resolve(__dirname, '../../../public/videos/ec-daikoku-plugin/js/eccube-core.js');
fs.writeFileSync(file, `/* EC-CUBE 4.3.1-p1 (GPL) — files shown read-only in the video. Generated by tools/snapshots/ec-daikoku-plugin/build-core.js */\nwindow.EC_CORE = ${JSON.stringify(out)};\n`);
