/*
 * news-data.json (fetch-news.js: the live おしらせ list) → public/videos/wp-cookpad-media/js/news-data.js
 * (window.NEWS_DATA: the rows of the video's data/news.csv and of the import in capture-wp.js).
 * The newest item (2026-11-11) is left out: the video (2026-11-06) writes it as a scheduled post.
 * Bodies: only the internal article the video shows (2026-03-22, article-20260322.html: the live page) — the others
 * are not fetched (the list does not show them).
 */
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '../../..');
const all = JSON.parse(fs.readFileSync(path.join(__dirname, 'news-data.json'), 'utf8'));
const art = fs.readFileSync(path.join(__dirname, 'article-20260322.html'), 'utf8');
const body0322 = art.slice(art.indexOf('<div class="body">') + 18, art.indexOf('</div>', art.indexOf('<div class="body">'))).trim();
const rows = all.filter((o) => o.date <= '2026-11-06').map((o) => {
  const internal = !o.external && o.link.startsWith('/news/');
  return {
    date: o.date,
    category: o.cats[0] || '',
    title: o.title,
    slug: internal ? decodeURIComponent(o.link.slice(6)) : '',
    url: o.external ? o.link : '',
    image: /thumb_noimg/.test(o.image) ? '' : o.image,
    body: o.date === '2026-03-22' && internal ? body0322 : '',
  };
});
const out = `/* the live おしらせ (info.cookpad.com/news) as rows of data/news.csv — generated by tools/snapshots/wp-cookpad-media/build-data.js */\nwindow.NEWS_DATA = ${JSON.stringify(rows)};\nwindow.NEWS_NEXT = ${JSON.stringify(all[0])};\n`;
fs.writeFileSync(path.join(ROOT, 'public/videos/wp-cookpad-media/js/news-data.js'), out);
console.log('rows', rows.length, 'internal', rows.filter((r) => r.slug).length, 'with url', rows.filter((r) => r.url).length);
