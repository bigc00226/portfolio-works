/*
 * The project files VS Code shows besides the customisation (js/customize-src.js): the shop's theme as build-theme.js
 * made it (the same files the local EC-CUBE of the captures runs) and EC-CUBE 4.3.1-p1's own docker-compose.yml /
 * composer.json (the docker-compose.yml with APP_ENV prod — the dev copy runs as production does).
 *
 *   node tools/snapshots/ec-koyama-kyugu/make-theme-src.js   → public/videos/ec-koyama-kyugu/js/theme-src.js
 */
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '../../..');
const RT = require(path.join(ROOT, 'tools/eccube/runtime'));
const BASE = path.join(RT.LOCAL, 'inst', 'base');
const T = (p) => fs.readFileSync(path.join(__dirname, 'theme', p), 'utf8');
const files = {
  'app/template/default/default_frame.twig': T('app/template/default/default_frame.twig'),
  'app/template/default/Product/detail.twig': T('app/template/default/Product/detail.twig'),
  'html/user_data/assets/css/customize.css': T('html/user_data/assets/css/customize.css'),
  'docker-compose.yml': fs.readFileSync(path.join(BASE, 'docker-compose.yml'), 'utf8')
    .replace('APP_ENV: "dev"', 'APP_ENV: "prod"     # 本番と同じ設定で確認（エラーは var/log/prod）')
    .replace('APP_DEBUG: 1', 'APP_DEBUG: 0'),
  'composer.json': fs.readFileSync(path.join(BASE, 'composer.json'), 'utf8'),
};
const out = path.join(ROOT, 'public/videos/ec-koyama-kyugu/js/theme-src.js');
fs.writeFileSync(out, `/* generated by tools/snapshots/ec-koyama-kyugu/make-theme-src.js — the shop's theme (rebuilt from the public HTML) and EC-CUBE's own files */\nwindow.KOYAMA_THEME = ${JSON.stringify(files, null, 1)};\n`);
console.log('wrote', out, Object.keys(files).map((k) => `${k} ${files[k].split('\n').length}`).join(', '));
