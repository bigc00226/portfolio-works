// The store-link (the shop's in-store stock system's side, reconstructed) as the video types it, in stages:
//   node tools/snapshots/ec-tackleberry-api/build-src.js  → public/videos/ec-tackleberry-api/js/link-src.js (window.TB_SRC; also require()-able)
// Source of truth: tools/snapshots/ec-tackleberry-api/store-link/ (the final files — they really run against the local EC-CUBE in capture-ec.js).
//   link.mjs  stage 1  OAuth2.0 (token, refresh) · GraphQL · authorize · stock · serve (/callback)
//             stage 2  + the ledger, pick(), verify() and the /webhook handler — with the header read as 'X-ECCUBE-Signature' (the mistake:
//                        Node gives header names in lower case, so the signature is never found → 401)
//             stage 3  the header fixed + ship
//             stage 4  + orders (the catch-up of orders whose WebHook never arrived) = the final file
//   graphql/update-stock.graphql  stage 1 without the stock_unlimited argument (the mistake: a required argument) · stage 2 = final
const fs = require('fs');
const path = require('path');
const DIR = path.join(__dirname, 'store-link');
const OUT = path.resolve(__dirname, '../../../public/videos/ec-tackleberry-api/js/link-src.js');
const read = (f) => fs.readFileSync(path.join(DIR, f), 'utf8').replace(/\r\n/g, '\n');

const FILES = ['link.mjs', 'lib/util.mjs', 'graphql/update-stock.graphql', 'graphql/order.graphql', 'graphql/orders.graphql', 'graphql/update-shipped.graphql', '.env.example'];
const files = Object.fromEntries(FILES.map((f) => [f, read(f)]));

const L = files['link.mjs'];
const cut = (text, from, to) => { const a = text.indexOf(from); const b = text.indexOf(to, a + 1); if (a < 0 || b < 0) throw new Error('no block ' + from.slice(0, 40)); return [text.slice(a, b), text.slice(0, a) + text.slice(b)]; };
const [A] = cut(L, '/* ---------------------------------------------------------- 在庫台帳・出荷指示 */', 'const page = ');
const [B] = cut(L, "    if (url.pathname === '/webhook'", '    res.writeHead(404).end();');
const [C] = cut(L, "if (cmd === 'orders') {", "if (cmd === 'ship') {");
const D = L.slice(L.indexOf("if (cmd === 'ship') {"));
const HO = '//   node link.mjs orders         新規受付の注文の取りこぼし確認（定期実行）\n';
const HS = '//   node link.mjs ship <csv>     店舗の出荷実績 → updateShipped（出荷完了メール）\n';
const BUG = ["req.headers['x-eccube-signature']", "req.headers['X-ECCUBE-Signature']"];
const s4 = L;
const s3 = s4.replace(C, '').replace(HO, '');
const s2 = s3.replace(D, '').replace(/\n+$/, '\n').replace(HS, '').replace(BUG[0], BUG[1]);
const s1 = s2.replace(A, '').replace(B.replace(BUG[0], BUG[1]), '').replace("const PICKED = 'var/picked.json';\n", '');
for (const [n, s] of Object.entries({ s1, s2, s3 })) if (s === L) throw new Error('stage ' + n + ' did not change');
const U = files['graphql/update-stock.graphql'];
const stockV1 = U.replace(', stock_unlimited: false', '');
if (stockV1 === U) throw new Error('update-stock v1 did not change');

// EC-CUBE 4.3.1-p1's bundled Api42 and the OAuth2 bundle it uses — opened read-only in the video, byte for byte from the EC-CUBE the captures run
const BASE = path.resolve(__dirname, '../../../../eccube-local/inst/base');
const CORE = ['app/Plugin/Api42/GraphQL/Mutation/UpdateProductStockMutation.php', 'app/Plugin/Api42/Service/WebHookService.php',
  'vendor/league/oauth2-server-bundle/src/Repository/ClientRepository.php'];
const core = Object.fromEntries(CORE.map((f) => [f, fs.readFileSync(path.join(BASE, f), 'utf8').replace(/\r\n/g, '\n').replace(/\n$/, '')]));
const SRC = { files, link: { 1: s1, 2: s2, 3: s3, 4: s4 }, blocks: { A, B, C, D, HO, HS, BUG }, stockV1, core };
fs.writeFileSync(OUT, `/* store-link (reconstructed in-store stock system side) — generated by tools/snapshots/ec-tackleberry-api/build-src.js from store-link/ */
(function (root) {
  var SRC = ${JSON.stringify(SRC)};
  if (typeof module !== 'undefined' && module.exports) module.exports = SRC; else root.TB_SRC = SRC;
})(this);
`);
console.log('wrote', OUT, Object.entries(SRC.link).map(([k, v]) => `stage ${k}: ${v.split('\n').length} lines`).join(', '));
