// Builds js/site-snapshot.js from a rendered capture of the live STUDIO site.
// (Normally run through tools/update-snapshot.js, which makes the capture first.)
//
//   node tools/build-snapshot.js <rendered.html> <stylesheet.css> [more.css ...]
//
// The stylesheets are STUDIO's own /_nuxt/*.css files, in document order.
//
// - keeps the exact rendered DOM of #__nuxt (STUDIO's markup, data-s-* attributes, classes)
// - keeps every STUDIO-generated <style> in document order (+ STUDIO base CSS)
// - downloads the image assets into assets/img/ and points the snapshot at them
// - rewrites viewport units (vh/dvh) to a CSS variable so the page can live inside an
//   editor canvas whose iframe is as tall as the whole page
const fs = require('fs');
const path = require('path');
const https = require('https');

const [renderedPath, ...cssPaths] = process.argv.slice(2);
if (!renderedPath || !cssPaths.length) {
  console.error('usage: node tools/build-snapshot.js <rendered.html> <stylesheet.css> [more.css ...]');
  process.exit(1);
}
const ROOT = path.resolve(__dirname, '../../../public/videos/studio-ysk'); // the video's folder
const IMG_DIR = path.join(ROOT, 'assets', 'img');
fs.mkdirSync(IMG_DIR, { recursive: true });
fs.mkdirSync(path.join(ROOT, 'js'), { recursive: true });

const html = fs.readFileSync(renderedPath, 'utf8');
const baseCss = cssPaths.map((p) => fs.readFileSync(p, 'utf8'));

// 1) all <style> blocks in document order
const styles = [];
html.replace(/<style[^>]*>([\s\S]*?)<\/style>/g, (_, css) => { styles.push(css); return ''; });

// 2) font stylesheets (Google Fonts + STUDIO-hosted A1 Gothic)
const fontLinks = [...html.matchAll(/<link[^>]+href="(https:\/\/fonts\.(?:googleapis\.com|studio\.design)[^"]+)"[^>]*>/g)]
  .map((m) => m[1].replace(/&amp;/g, '&'));

// 3) body markup of #__nuxt without scripts / styles
const start = html.indexOf('<div id="__nuxt">');
const end = html.indexOf('<div id="teleports">');
let body = html.slice(start, end > 0 ? end : undefined);
body = body.replace(/<script[\s\S]*?<\/script>/g, '').replace(/<style[^>]*>[\s\S]*?<\/style>/g, '');

// 4) viewport units -> variable (editor canvas sets --demo-vh; live view leaves the fallback)
const vhFix = (css) => css.replace(/(\d+(?:\.\d+)?)(d|s|l)?vh\b/g, (_, n, p) => `calc(${n} * var(--demo-vh, 1${p || ''}vh))`);
const allCss = [...baseCss, ...styles].map(vhFix).join('\n');

// 5) elements that carry a STUDIO "appear" animation
const appearIds = [...new Set([...allCss.matchAll(/\.sd\[data-s-([0-9a-f-]+)\]\.appear \{/g)].map((m) => m[1]))];

// 6) images -> local files (the page's own images and the CMS posts' covers)
const urls = [...new Set([...(allCss + body).matchAll(/https:\/\/storage\.googleapis\.com\/studio-(?:design-asset-files|cms-assets)\/[^"')\s&]+/g)].map((m) => m[0]))];
const fetchTo = (url, dest) => new Promise((resolve, reject) => {
  if (fs.existsSync(dest)) return resolve();
  https.get(url, (res) => {
    if (res.statusCode !== 200) return reject(new Error(url + ' -> ' + res.statusCode));
    const f = fs.createWriteStream(dest);
    res.pipe(f);
    f.on('finish', () => f.close(resolve));
  }).on('error', reject);
});

(async () => {
  let css = allCss;
  for (const url of urls) {
    const name = url.split('/').pop().replace(/^s-\d+x\d+_v-f?r?ms_webp_/, '');
    await fetchTo(url, path.join(IMG_DIR, name));
    css = css.split(url).join('assets/img/' + name);
    body = body.split(url).join('assets/img/' + name);
    console.log('img', name);
  }
  // photos the page takes from STUDIO's Unsplash library (the URL with its query, as the page uses it)
  const unsplash = [...new Set([...(css + body).matchAll(/https:\/\/images\.unsplash\.com\/photo-[0-9a-f-]+\?[^"')\s]+/g)].map((m) => m[0]))];
  for (const url of unsplash) {
    const name = 'unsplash-' + url.match(/photo-([0-9a-f-]+)/)[1] + '.jpg';
    await fetchTo(url.replace(/&amp;/g, '&'), path.join(IMG_DIR, name));
    css = css.split(url).join('assets/img/' + name);
    body = body.split(url).join('assets/img/' + name);
    console.log('img', name);
  }
  const snapshot = { fontLinks, css, body, appearIds, capturedAt: new Date().toISOString() };
  fs.writeFileSync(
    path.join(ROOT, 'js', 'site-snapshot.js'),
    '/* Auto-generated by tools/build-snapshot.js from https://ysk-co-jp.studio.site/ */\n' +
    'window.SITE_SNAPSHOT = ' + JSON.stringify(snapshot) + ';\n'
  );
  console.log('styles', styles.length, 'appear', appearIds.length, 'fonts', fontLinks.length, 'body', body.length, 'css', css.length);
})().catch((e) => { console.error(e); process.exit(1); });
