// EC-CUBE 2's own source files the video opens in VS Code (read only — the customisation goes into data/class_extends),
// copied byte for byte from the EC-CUBE 2 the captures run (eccube2-weekly-20261110):
//   node tools/snapshots/ec-garage-forms/build-core.js   → public/videos/ec-garage-forms/js/eccube-core.js (window.EC_CORE)
const fs = require('fs');
const path = require('path');
const SRC = path.resolve(__dirname, '../../../../eccube-local/src2w/ec-cube2');
const FILES = ['data/class/SC_Fpdf.php', 'data/class/pages/admin/order/LC_Page_Admin_Order_Pdf.php', 'data/class_extends/README.md'];
const out = {};
for (const f of FILES) out[f] = fs.readFileSync(path.join(SRC, f), 'utf8').replace(/\r\n/g, '\n');
const file = path.resolve(__dirname, '../../../public/videos/ec-garage-forms/js/eccube-core.js');
fs.writeFileSync(file, `/* EC-CUBE 2 (eccube2-weekly-20261110, GPL) — files shown read-only in the video. Generated by tools/snapshots/ec-garage-forms/build-core.js */\nwindow.EC_CORE = ${JSON.stringify(out)};\n`);
console.log('wrote', file, Object.keys(out).map((k) => `${k} ${out[k].split('\n').length} lines`).join(', '));
